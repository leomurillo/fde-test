#!/usr/bin/env python3
"""Validate data/taxonomy.yaml and render docs/taxonomy.md from it.

  python tools/taxonomy.py --check            # validate only (non-zero exit on error)
  python tools/taxonomy.py --check --render   # validate, then regenerate docs/taxonomy.md
  python tools/taxonomy.py --bank 300         # show MCQ allocation for a different bank size

Requires PyYAML.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
TAXONOMY = REPO_ROOT / "data" / "taxonomy.yaml"
TERMINOLOGY = REPO_ROOT / "data" / "terminology.yaml"
OUT = REPO_ROOT / "docs" / "taxonomy.md"


def largest_remainder(total: int, weights: list[float]) -> list[int]:
    """Split `total` into integers proportional to `weights`, summing exactly to `total`."""
    s = sum(weights)
    raw = [total * w / s for w in weights]
    floors = [int(r) for r in raw]
    leftover = total - sum(floors)
    order = sorted(range(len(raw)), key=lambda i: raw[i] - floors[i], reverse=True)
    for i in order[:leftover]:
        floors[i] += 1
    return floors


def validate(tax: dict) -> list[str]:
    errors = []
    domains = tax["domains"]
    total = sum(d["weight"] for d in domains)
    if total != 100:
        errors.append(f"domain weights sum to {total}, expected 100")

    jd_items = set(tax["jd_coverage_items"])
    ext = set(tax["external_sources"])
    formats = {f["id"] for f in tax["formats"]}
    covered: set[str] = set()
    tags = Counter()

    for d in domains:
        shares = sum(s["share"] for s in d["subtopics"])
        if shares != 100:
            errors.append(f"{d['id']}: subtopic shares sum to {shares}, expected 100")
        for src in d.get("sources", {}).get("external", []):
            if src not in ext:
                errors.append(f"{d['id']}: unknown external source '{src}'")
        for s in d["subtopics"]:
            tags[s["tag"]] += 1
            if not s["id"].startswith(d["id"] + "."):
                errors.append(f"{s['id']}: id does not belong to domain {d['id']}")
            for j in s.get("jd", []):
                if j not in jd_items:
                    errors.append(f"{s['id']}: unknown JD item '{j}'")
                covered.add(j)

    for tag, n in tags.items():
        if n > 1:
            errors.append(f"tag '{tag}' used {n} times")
    for j in sorted(jd_items - covered):
        errors.append(f"JD item '{j}' is not covered by any subtopic")
    for x in tax["cross_cutting"]:
        for f in x["formats"]:
            if f not in formats:
                errors.append(f"{x['id']}: unknown format '{f}'")
    return errors


def jd_coverage(tax: dict) -> dict[str, list[str]]:
    cov: dict[str, list[str]] = {j: [] for j in tax["jd_coverage_items"]}
    for d in tax["domains"]:
        for s in d["subtopics"]:
            for j in s.get("jd", []):
                cov[j].append(s["id"])
    return cov


def render(tax: dict, terms: dict, bank: int) -> str:
    domains = tax["domains"]
    dom_counts = largest_remainder(bank, [d["weight"] for d in domains])
    L: list[str] = []
    w = L.append

    w("# FDE Exam Topic Taxonomy (weighted)")
    w("")
    w(f"<!-- Generated by tools/taxonomy.py from data/taxonomy.yaml (v{tax['version']}, {tax['updated']}). "
      "Edit the YAML, not this file. -->")
    w("")
    w(tax["scope"].strip())
    w("")
    w("Weights are the approximate share of a full examination. They come from four kinds of evidence: "
      "the job description's coverage requirements, the syllabi of existing FDE and adjacent "
      "certifications, how much each handbook covers the topic, and which CandiTech question formats "
      "can assess it. The reasoning is in [research.md](research.md); each domain's rationale is below.")
    w("")
    w("## Domains at a glance")
    w("")
    w(f"| # | Domain | Weight | MCQs in a {bank}-item bank | Subtopics |")
    w("|---|---|---:|---:|---:|")
    for d, n in zip(domains, dom_counts):
        w(f"| {d['id']} | {d['name']} | {d['weight']}% | {n} | {len(d['subtopics'])} |")
    w(f"| | **Total** | **{sum(d['weight'] for d in domains)}%** | **{sum(dom_counts)}** | "
      f"**{sum(len(d['subtopics']) for d in domains)}** |")
    w("")
    w("Grouped differently:")
    w("")
    groups = [
        ("Field craft: role, discovery, stakeholders", ["D1", "D2", "D3"]),
        ("AI engineering: LLM, RAG/data, agents, evals", ["D4", "D5", "D6", "D7"]),
        ("Enterprise production: governance, integration, deployment, operations", ["D8", "D9", "D10", "D11"]),
    ]
    by_id = {d["id"]: d for d in domains}
    for name, ids in groups:
        w(f"- **{name}**: {sum(by_id[i]['weight'] for i in ids)}%")
    w("")

    w("## Domains and subtopics")
    w("")
    w("`Tag` is the identifier used to tag questions. `Eff.` is the effective weight in the whole exam "
      "(domain weight × subtopic share). `MCQs` is the target count in the bank.")
    w("")
    for d, n in zip(domains, dom_counts):
        sub_counts = largest_remainder(n, [s["share"] for s in d["subtopics"]])
        w(f"### {d['id']} · {d['name']} — {d['weight']}%")
        w("")
        w(f"*Why this weight:* {d['rationale'].strip()}")
        w("")
        src = d.get("sources", {})
        parts = []
        if src.get("richardxu"):
            parts.append("Richard Xu " + ", ".join(src["richardxu"]))
        if src.get("goday"):
            parts.append("goday " + ", ".join(src["goday"]))
        if src.get("external"):
            parts.append("external: " + ", ".join(f"[{e}]({tax['external_sources'][e]})" for e in src["external"]))
        w(f"*Sources:* {'; '.join(parts)}")
        w("")
        w("| ID | Tag | Subtopic | Share | Eff. | MCQs | Key concepts |")
        w("|---|---|---|---:|---:|---:|---|")
        for s, c in zip(d["subtopics"], sub_counts):
            eff = d["weight"] * s["share"] / 100
            concepts = "<br>".join("• " + k for k in s["concepts"])
            w(f"| {s['id']} | `{s['tag']}` | {s['name']} | {s['share']}% | {eff:.1f}% | {c} | {concepts} |")
        w("")

    w("## Cross-cutting competencies")
    w("")
    w("These are assessed mainly through question *formats*, not MCQ counts. They are where CandiTech's "
      "embedded-AI sections, SQL and code questions, and AI-graded open answers come in.")
    w("")
    w("| ID | Competency | Assessed via | Notes |")
    w("|---|---|---|---|")
    for x in tax["cross_cutting"]:
        w(f"| `{x['id']}` | {x['name']} | {', '.join(x['formats'])} | {x.get('desc', '').strip()} |")
    w("")

    w("## Question formats (mapped to CandiTech)")
    w("")
    w("| Format | CandiTech equivalent | Grading | Notes |")
    w("|---|---|---|---|")
    for f in tax["formats"]:
        w(f"| `{f['id']}` | {f['canditech']} | {f['grading']} | {f.get('note', '')} |")
    w("")
    w("Cognitive levels to tag each question with: " +
      "; ".join(f"`{c['id']}` ({c['desc'].rstrip('.')})" for c in tax["cognitive_levels"]) + ".")
    w("")

    w("## Job-description coverage check")
    w("")
    w("Every non-generic item in the Gorilla Logic JD maps to at least one subtopic. `tools/taxonomy.py --check` "
      "fails if one doesn't. Generic soft skills, seniority, and language or frontend-framework choices are "
      "left out on purpose.")
    w("")
    w("| JD item | Covered by |")
    w("|---|---|")
    for j, subs in jd_coverage(tax).items():
        w(f"| **{j}**: {tax['jd_coverage_items'][j]} | {', '.join(subs)} |")
    w("")

    w("## Terminology policy")
    w("")
    w("Questions test principles and mainstream vocabulary. Labels coined by either handbook are never "
      "the thing being tested. Full register: [`data/terminology.yaml`](../data/terminology.yaml).")
    w("")
    w("| Term | Source | Status | Policy | Mainstream reading |")
    w("|---|---|---|---|---|")
    for t in terms["terms"]:
        main = (t.get("mainstream") or t.get("note") or "").strip().replace("\n", " ")
        w(f"| {t['term']} | {t['source']} | {t['status']} | {t['policy']} | {main} |")
    w("")
    return "\n".join(L)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="validate the taxonomy")
    ap.add_argument("--render", action="store_true", help=f"write {OUT.relative_to(REPO_ROOT)}")
    ap.add_argument("--bank", type=int, help="MCQ bank size (default: mcq_bank_target from the YAML)")
    args = ap.parse_args()

    tax = yaml.safe_load(TAXONOMY.read_text(encoding="utf-8"))
    terms = yaml.safe_load(TERMINOLOGY.read_text(encoding="utf-8"))
    bank = args.bank or tax["mcq_bank_target"]

    errors = validate(tax)
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        sys.exit(1)
    if args.check:
        n_sub = sum(len(d["subtopics"]) for d in tax["domains"])
        print(f"ok: {len(tax['domains'])} domains, {n_sub} subtopics, "
              f"{len(tax['jd_coverage_items'])} JD items covered, {len(terms['terms'])} terms")

    if args.render:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(render(tax, terms, bank) + "\n", encoding="utf-8")
        print(f"wrote {OUT.relative_to(REPO_ROOT)}")
    elif not args.check:
        counts = largest_remainder(bank, [d["weight"] for d in tax["domains"]])
        for d, n in zip(tax["domains"], counts):
            print(f"{d['id']:<4} {d['weight']:>3}%  {n:>4}  {d['name']}")
        print(f"{'':<4} {'':>4}  {sum(counts):>4}  total")


if __name__ == "__main__":
    main()
